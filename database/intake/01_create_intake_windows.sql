DO $precondition$
BEGIN
  IF pg_catalog.to_regclass('public.intake_windows') IS NOT NULL
    OR pg_catalog.to_regclass('public.intake_requests') IS NOT NULL
  THEN
    RAISE EXCEPTION 'Las tablas intake ya existen; revisar antes de aplicar.';
  END IF;

  IF pg_catalog.to_regprocedure(
    'public.create_student_invitation(bigint,interval)'
  ) IS NULL THEN
    RAISE EXCEPTION 'Falta create_student_invitation(bigint,interval).';
  END IF;

  IF pg_catalog.to_regprocedure('public.consume_student_invitation(text)') IS NULL
    OR pg_catalog.to_regclass('public.student_account_invitations') IS NULL
  THEN
    RAISE EXCEPTION 'Falta el contrato completo de invitaciones individuales.';
  END IF;

  IF pg_catalog.to_regprocedure('extensions.gen_random_bytes(integer)') IS NULL
    OR pg_catalog.to_regprocedure('extensions.digest(bytea,text)') IS NULL
    OR pg_catalog.to_regprocedure('extensions.digest(text,text)') IS NULL
    OR pg_catalog.to_regprocedure('pg_catalog.gen_random_uuid()') IS NULL
  THEN
    RAISE EXCEPTION 'Faltan dependencias criptograficas requeridas.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_attribute AS attributes
    WHERE attributes.attrelid = 'public.student_account_invitations'::regclass
      AND attributes.attname = 'id'
      AND attributes.atttypid = 'uuid'::regtype
      AND attributes.attnotnull AND NOT attributes.attisdropped
  ) THEN
    RAISE EXCEPTION 'student_account_invitations.id no cumple el contrato uuid.';
  END IF;
END;
$precondition$;

CREATE TABLE public.intake_windows (
  id uuid PRIMARY KEY DEFAULT pg_catalog.gen_random_uuid(),
  name text NOT NULL,
  public_token_hash text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'open',
  expires_at timestamptz NOT NULL,
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz NULL,
  message text NULL,
  CONSTRAINT intake_windows_name_check
    CHECK (char_length(btrim(name)) BETWEEN 3 AND 120),
  CONSTRAINT intake_windows_token_hash_check
    CHECK (public_token_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT intake_windows_status_check
    CHECK (status IN ('open', 'closed', 'expired', 'revoked')),
  CONSTRAINT intake_windows_message_check
    CHECK (message IS NULL OR char_length(btrim(message)) BETWEEN 1 AND 500),
  CONSTRAINT intake_windows_closed_state_check
    CHECK ((status = 'open' AND closed_at IS NULL) OR (status <> 'open' AND closed_at IS NOT NULL))
);

CREATE TABLE public.intake_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  intake_window_id uuid NOT NULL REFERENCES public.intake_windows(id) ON DELETE CASCADE,
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text NOT NULL,
  phone text NULL,
  requested_voice text NULL,
  requested_role text NOT NULL DEFAULT 'student',
  notes text NULL,
  status text NOT NULL DEFAULT 'pending',
  reviewed_by uuid NULL REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz NULL,
  rejection_reason text NULL,
  member_id bigint NULL REFERENCES public.members(id) ON DELETE SET NULL,
  invitation_id uuid NULL REFERENCES public.student_account_invitations(id) ON DELETE SET NULL,
  invitation_delivery_status text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT intake_requests_first_name_check
    CHECK (char_length(btrim(first_name)) BETWEEN 1 AND 100),
  CONSTRAINT intake_requests_last_name_check
    CHECK (char_length(btrim(last_name)) BETWEEN 1 AND 150),
  CONSTRAINT intake_requests_email_check
    CHECK (
      email = lower(btrim(email))
      AND char_length(email) BETWEEN 3 AND 320
      AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    ),
  CONSTRAINT intake_requests_phone_check
    CHECK (phone IS NULL OR char_length(btrim(phone)) BETWEEN 7 AND 30),
  CONSTRAINT intake_requests_voice_check
    CHECK (requested_voice IS NULL OR requested_voice IN ('Soprano', 'Contralto', 'Tenor', 'Bajo', 'Otra')),
  CONSTRAINT intake_requests_requested_role_check
    CHECK (requested_role IN ('student', 'member')),
  CONSTRAINT intake_requests_notes_check
    CHECK (notes IS NULL OR char_length(btrim(notes)) BETWEEN 1 AND 1000),
  CONSTRAINT intake_requests_status_check
    CHECK (status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT intake_requests_rejection_check
    CHECK (
      (status = 'rejected' AND rejection_reason IS NOT NULL AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL)
      OR (status <> 'rejected' AND rejection_reason IS NULL)
    ),
  CONSTRAINT intake_requests_approval_check
    CHECK (
      status <> 'approved'
      OR (member_id IS NOT NULL AND invitation_id IS NOT NULL AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL)
    ),
  CONSTRAINT intake_requests_delivery_check
    CHECK (invitation_delivery_status IS NULL OR invitation_delivery_status IN ('manual_pending', 'sent'))
);

CREATE UNIQUE INDEX intake_requests_pending_email_unique
  ON public.intake_requests (intake_window_id, lower(email))
